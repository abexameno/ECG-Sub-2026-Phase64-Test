export async function formatAsPdf(
    content: GeneratedContent, 
    assessmentExportType: AssessmentExportType = AssessmentExportType.QuestionsAndAnswers, 
    headerInfo?: ExportHeaderInfo, 
    artifact?: ContentArtifact
): Promise<void> {
    if (!isResourcePdfCompatible(content)) {
        throw new Error('This resource cannot be exported as PDF.');
    }

    const pdfMake = await getPdfMakeInstance();
    const docDefinition = buildPdfDocDefinition(content, assessmentExportType, headerInfo, artifact);
    const filename = generateFilename(content, 'pdf', assessmentExportType);

    pdfMake.createPdf(docDefinition).download(filename);

    AuditService.log('PDF_EXPORT', artifact?.schoolId || content.metadata?.schoolId, {
        title: content.title,
        contentType: content.metadata?.contentType,
        grade: content.metadata?.grade,
        subject: content.metadata?.subject,
        timestamp: new Date().toISOString()
    });
}

export async function formatMergedAsPdf(
    contents: GeneratedContent[], 
    options?: {
        schoolName?: string;
        schoolLogo?: string;
        county?: string;
        academicYear?: string;
        assessmentExportType?: AssessmentExportType;
        headerInfo?: ExportHeaderInfo;
        userId?: string;
        schoolId?: string;
    }
): Promise<{ success: boolean; filename: string; documentCount: number }> {
    if (!contents || contents.length === 0) {
        throw new Error('No resources selected.');
    }

    const compatibleItems = contents.filter(isResourcePdfCompatible);
    if (compatibleItems.length === 0) {
        throw new Error('Some selected resources cannot be exported as PDF.');
    }

    const pdfMake = await getPdfMakeInstance();
    const docDefinition = buildMergedPdfDocDefinition(compatibleItems, options);
    const filename = generateMergedFilename(compatibleItems, options?.schoolName);

    pdfMake.createPdf(docDefinition).download(filename);

    AuditService.log('PDF_MERGE_EXPORT', options?.schoolId, {
        documentCount: compatibleItems.length,
        userId: options?.userId,
        schoolName: options?.schoolName,
        titles: compatibleItems.map(c => c.title),
        timestamp: new Date().toISOString()
    });

    return {
        success: true,
        filename,
        documentCount: compatibleItems.length
    };
}

