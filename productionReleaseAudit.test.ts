// Standard Jest test
import { 
  PDF_WATERMARK_TEXT, 
  PDF_WATERMARK_CONFIG, 
  isResourcePdfCompatible, 
  generateMergedFilename, 
  buildPdfDocDefinition, 
  buildMergedPdfDocDefinition 
} from './services/pdfService.ts';
import { GeneratedContent, ContentType, AssessmentExportType, QuestionType } from './types.ts';
import { ContentArtifact } from './types/artifact.ts';
import { AuditService } from './services/auditService.ts';
import { ContentArtifactRepository } from './services/contentArtifactRepository.ts';

describe('Production Release Audit — Phase 45 & System Verification', () => {
  const sampleSchoolA = 'St. Joseph Academy';
  const sampleSchoolB = 'Kilifi Junior School';

  const validResourceA: GeneratedContent = {
    id: 'res-001',
    title: 'Grade 7 Mathematics - Term 1 - Lesson Notes',
    body: '# Introduction to Algebra\n\nAlgebra involves symbols and numbers.',
    metadata: {
      grade: 'Grade 7',
      subject: 'Mathematics',
      contentType: ContentType.LessonNotes,
      term: 'Term 1',
      terms: ['Term 1'],
      schoolId: 'school-a-123'
    },
    savedAt: new Date().toISOString()
  };

  const validAssessmentResource: GeneratedContent = {
    id: 'res-002',
    title: 'Grade 8 Science - Assessment',
    questions: [
      {
        questionText: 'What is photosynthesis?',
        questionType: QuestionType.MultipleChoice,
        options: ['Light conversion', 'Digestion', 'Respiration', 'Excretion'],
        correctAnswer: 'A',
        explanation: 'Process by which plants convert light energy.',
        marks: 1
      },
      {
        questionText: 'Describe the stages of water cycle.',
        questionType: QuestionType.Structured,
        correctAnswer: 'Evaporation, condensation, precipitation, collection.',
        explanation: 'Full description required for complete marks.',
        marks: 4
      }
    ],
    metadata: {
      grade: 'Grade 8',
      subject: 'Integrated Science',
      contentType: ContentType.Assessment,
      term: 'Term 1',
      terms: ['Term 1'],
      schoolId: 'school-a-123'
    },
    savedAt: new Date().toISOString()
  };

  const validSchemeOfWork: GeneratedContent = {
    id: 'res-003',
    title: 'Grade 7 Pre-Technical Studies - Scheme of Work',
    schemeOfWorkData: {
      term: 'Term 1',
      year: '2026',
      entries: [
        {
          week: '1',
          lesson: '1',
          strand: 'Safety in Work Environment',
          subStrand: 'Personal Safety',
          learningOutcomes: 'Identify personal safety gear',
          inquiryQuestions: 'Why is safety gear important?',
          learningExperiences: 'Learners discuss safety goggles and gloves',
          learningResources: 'Safety manual, charts',
          assessment: 'Oral questions',
          remarks: 'Completed'
        }
      ]
    },
    metadata: {
      grade: 'Grade 7',
      subject: 'Pre-Technical Studies',
      contentType: ContentType.SchemeOfWork,
      term: 'Term 1',
      terms: ['Term 1'],
      schoolId: 'school-a-123'
    },
    savedAt: new Date().toISOString()
  };

  const emptyCorruptResource: GeneratedContent = {
    id: 'res-corrupt',
    title: '',
    metadata: undefined
  };

  test('Phase 45 Watermark: Exact text, opacity, and styling compliance', () => {
    expect(PDF_WATERMARK_TEXT).toBe('Generated by Exameno ECG');
    expect(PDF_WATERMARK_CONFIG.text).toBe('Generated by Exameno ECG');
    expect(PDF_WATERMARK_CONFIG.opacity).toBeCloseTo(0.08, 2);
    expect(PDF_WATERMARK_CONFIG.color).toBe('#475569');
  });

  test('Resource compatibility validation correctly identifies valid vs empty/corrupt items', () => {
    expect(isResourcePdfCompatible(validResourceA)).toBe(true);
    expect(isResourcePdfCompatible(validAssessmentResource)).toBe(true);
    expect(isResourcePdfCompatible(validSchemeOfWork)).toBe(true);
    expect(isResourcePdfCompatible(emptyCorruptResource)).toBe(false);
    expect(isResourcePdfCompatible(null)).toBe(false);
    expect(isResourcePdfCompatible({})).toBe(false);
  });

  test('Standardized Merged Filename format matches requirements', () => {
    const filename = generateMergedFilename([validResourceA, validAssessmentResource], sampleSchoolA, 2026);
    expect(filename).toBe('St. Joseph Academy - Selected Resources - Term 1 - 2026.pdf');
  });

  test('Single Document Definition includes watermark and official metadata', () => {
    const docDef = buildPdfDocDefinition(validResourceA, AssessmentExportType.QuestionsAndAnswers, {
      schoolName: sampleSchoolA
    });
    expect(docDef.watermark).toBeDefined();
    expect(docDef.watermark.text).toBe('Generated by Exameno ECG');
    expect(docDef.content).toBeDefined();
    expect(docDef.pageOrientation).toBe('portrait');
  });

  test('Tabular Document Definition correctly defaults to landscape orientation', () => {
    const docDef = buildPdfDocDefinition(validSchemeOfWork, AssessmentExportType.QuestionsAndAnswers, {
      schoolName: sampleSchoolA
    });
    expect(docDef.pageOrientation).toBe('landscape');
  });

  test('Merged Document Definition bundles multiple items with clear separation and zero AI call', () => {
    const mergedDoc = buildMergedPdfDocDefinition([validResourceA, validAssessmentResource], {
      schoolName: sampleSchoolA,
      assessmentExportType: AssessmentExportType.QuestionsAndAnswers
    });

    expect(mergedDoc.watermark.text).toBe('Generated by Exameno ECG');
    expect(mergedDoc.content.length).toBeGreaterThan(1);
    
    // Check that second item has a pageBreak before it
    const pageBreakElement = mergedDoc.content.find((el: any) => el.pageBreak === 'before');
    expect(pageBreakElement).toBeDefined();
  });

  test('Audit Service records PDF exports and Merged Exports without error', () => {
    const logSpy = jest.spyOn(AuditService, 'log');
    
    AuditService.log('PDF_EXPORT', 'school-a-123', {
      title: validResourceA.title,
      contentType: validResourceA.metadata?.contentType
    });

    AuditService.log('PDF_MERGE_EXPORT', 'school-a-123', {
      documentCount: 2,
      schoolName: sampleSchoolA
    });

    expect(logSpy).toHaveBeenCalledWith('PDF_EXPORT', 'school-a-123', expect.any(Object));
    expect(logSpy).toHaveBeenCalledWith('PDF_MERGE_EXPORT', 'school-a-123', expect.any(Object));
    logSpy.mockRestore();
  });

  test('School Isolation: Artifact Repository enforces school-scoped boundaries', () => {
    ContentArtifactRepository.clearStore();
    
    // Use valid school profiles registered in SchoolConfigService
    const schoolA = 'school-a';
    const schoolB = 'school-b';

    const artifactA: ContentArtifact = {
      id: 'art-001',
      version: 1,
      schoolId: schoolA,
      artifactType: 'scheme_of_work',
      title: 'Mathematics Grade 7 SOW',
      gradeLevelId: 'Grade 7',
      learningAreaId: 'la-math',
      curriculumReferences: [{
        subject: 'Mathematics',
        grade: 'Grade 7',
        strand: 'Numbers',
        subStrand: 'Fractions',
        learningOutcomes: ['Add fractions']
      }],
      content: { sample: 'data' },
      status: 'validated',
      source: 'ai_generated',
      generationMetadata: {
        model: 'gemini-2.5-flash',
        promptTokens: 100,
        completionTokens: 200,
        durationMs: 450,
        appliedRules: ['KICD_ALIGNED']
      },
      createdAt: new Date().toISOString(),
      updatedAt: new Date().toISOString()
    };

    const artifactB: ContentArtifact = {
      id: 'art-002',
      version: 1,
      schoolId: schoolB,
      artifactType: 'lesson_plan',
      title: 'Integrated Science Lesson Plan',
      gradeLevelId: 'Grade 8',
      learningAreaId: 'la-sci',
      curriculumReferences: [{
        subject: 'Integrated Science',
        grade: 'Grade 8',
        strand: 'Living Things',
        subStrand: 'Plants',
        learningOutcomes: ['Describe photosynthesis']
      }],
      content: { sample: 'data' },
      status: 'validated',
      source: 'ai_generated',
      generationMetadata: {
        model: 'gemini-2.5-flash',
        promptTokens: 100,
        completionTokens: 200,
        durationMs: 450,
        appliedRules: ['KICD_ALIGNED']
      },
      createdAt: new Date().toISOString(),
      updatedAt: new Date().toISOString()
    };

    ContentArtifactRepository.save(artifactA);
    ContentArtifactRepository.save(artifactB);

    const schoolAList = ContentArtifactRepository.list(schoolA);
    expect(schoolAList.length).toBe(1);
    expect(schoolAList[0].id).toBe('art-001');
    expect(schoolAList[0].schoolId).toBe(schoolA);

    const schoolBList = ContentArtifactRepository.list(schoolB);
    expect(schoolBList.length).toBe(1);
    expect(schoolBList[0].id).toBe('art-002');
    expect(schoolBList[0].schoolId).toBe(schoolB);

    // Cross-school direct ID retrieval MUST throw security violation
    expect(() => {
      ContentArtifactRepository.getById('art-001', schoolB);
    }).toThrow(/Security Violation: Access denied/);
  });
});
